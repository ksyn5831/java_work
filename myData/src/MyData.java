public class MyData {

//    항상 시작은 클래스로 시작하고 끝날 떄도 클래스로 시작한다.
//         변수의 종류는 정수, 실수, 문자열, 부울 타입
//    정수: int(20억), long(그 이상)
//    실수: double
//         참것짓(부울타입): boolean
//    소문자로 시작하는 데이터 타입: primitive type(원시타입)
//    문자: String
    public static void main(String[] args) {
        String name = "김서연";
        int age = 22;
        String myphonenumber = "010 - 5835 - 2248";
        System.out.println("이름 :" + name);
        System.out.println("나이 : " + age);
        System.out.println("전화번호 : " + myphonenumber);
    }
}
